    // Build a single sensor's status block into `parent[kind]`. Same
    // shape as the /api/system_status sensor section so the SPA can
    // patch entries in place from a WS `sensor_update` event or read
    // them in bulk from the REST snapshot. Returns the timestamp of
    // the most recent reading (0 if no valid reading yet) so callers
    // can dedupe.
    static uint32_t fill_sensor_block(JsonObject parent, const char* kind) {
      JsonObject o = parent[kind].to<JsonObject>();
      if (strcmp(kind, "gps") == 0) {
        const Sensors::L76K::Fix f = Sensors::L76K::last_fix();
        o["model"]        = Sensors::L76K::model_name();
        o["available"]    = Sensors::L76K::has_serial();
        // GPS is presented as a sensor in the popover (enable/interval
        // controls alongside BME280/QMC6310/IMU), but its config is
        // owned by TimeManager since it doubles as a time source. Pull
        // those fields here so the SPA's sensor-config row can render
        // without a second fetch.
        {
          const auto gcfg = Clock::Manager::get_config(Clock::Manager::Source::GPS);
          o["enabled"]     = gcfg.enabled;
          o["interval_ms"] = (uint32_t)gcfg.interval_s * 1000UL;
        }
        o["valid"]        = f.valid;
        o["latitude"]     = f.latitude_deg;
        o["longitude"]    = f.longitude_deg;
        o["speed_knots"]  = f.speed_knots;
        o["heading"]      = f.heading_deg;
        o["unix_ms"]      = (uint64_t)(f.unix_epoch * 1000.0);
        // Raw device-millis snapshots, NOT "X seconds ago" deltas. The
        // SPA subtracts these from its clock anchor every render tick
        // so "Last fix 12 s ago" labels tick up live without a refetch.
        // -1 sentinel = "never received."
        o["fix_received_ms"] = f.fix_received_ms == 0 ? -1 : (long)f.fix_received_ms;
        o["last_byte_ms"]    = f.last_byte_ms    == 0 ? -1 : (long)f.last_byte_ms;
        o["powered"]      = Sensors::L76K::is_powered();
        switch (Sensors::L76K::pulse_state()) {
          case Sensors::L76K::PulseState::Acquiring: o["pulse_state"] = "acquiring"; break;
          default:                              o["pulse_state"] = "idle";      break;
        }
        return f.fix_received_ms;
      }
      if (strcmp(kind, "environment") == 0) {
        const Sensors::BME280::Reading r = Sensors::BME280::last_reading();
        // Driver supplies the chip name — so swapping for a BMP280 /
        // BME680 variant in the future is a one-line driver change.
        o["model"]       = Sensors::BME280::model_name();
        o["available"]   = Sensors::BME280::present();
        o["enabled"]     = Sensors::BME280::enabled();
        o["interval_ms"] = (uint32_t)Sensors::BME280::interval_ms();
        o["valid"]       = r.valid;
        if (r.valid) {
          o["temp_c"]       = r.temp_c;
          o["humidity_pct"] = r.humidity_pct;
          o["pressure_pa"]  = r.pressure_pa;
          o["taken_ms"]     = (uint32_t)r.taken_ms;
        }
        if (Sensors::BME280::present()) o["address"] = Sensors::BME280::address();
        return r.taken_ms;
      }
      if (strcmp(kind, "magnetometer") == 0) {
        const Sensors::QMC6310::Reading r = Sensors::QMC6310::last_reading();
        o["model"]       = Sensors::QMC6310::model_name();
        o["available"]   = Sensors::QMC6310::present();
        o["enabled"]     = Sensors::QMC6310::enabled();
        o["interval_ms"] = (uint32_t)Sensors::QMC6310::interval_ms();
        o["valid"]       = r.valid;
        if (r.valid) {
          o["heading_deg"] = r.heading_deg;
          o["x_uT"]        = r.x_uT;
          o["y_uT"]        = r.y_uT;
          o["z_uT"]        = r.z_uT;
          o["taken_ms"]    = (uint32_t)r.taken_ms;
        }
        if (Sensors::QMC6310::present()) o["address"] = Sensors::QMC6310::address();
        return r.taken_ms;
      }
      if (strcmp(kind, "imu") == 0) {
        const Sensors::QMI8658::Reading r = Sensors::QMI8658::last_reading();
        o["model"]       = Sensors::QMI8658::model_name();
        o["available"]   = Sensors::QMI8658::present();
        o["enabled"]     = Sensors::QMI8658::enabled();
        o["interval_ms"] = (uint32_t)Sensors::QMI8658::interval_ms();
        o["valid"]       = r.valid;
        if (r.valid) {
          o["accel_x_g"]  = r.accel_x_g;
          o["accel_y_g"]  = r.accel_y_g;
          o["accel_z_g"]  = r.accel_z_g;
          o["gyro_x_dps"] = r.gyro_x_dps;
          o["gyro_y_dps"] = r.gyro_y_dps;
          o["gyro_z_dps"] = r.gyro_z_dps;
          o["temp_c"]     = r.temp_c;
          o["taken_ms"]   = (uint32_t)r.taken_ms;
        }
        return r.taken_ms;
      }
      return 0;
    }

    // Build the system-status payload (storage / rtc / sensors /
    // outbound_caps / battery) into `root`. Single source of truth
    // shared between the WS `hello` frame and the periodic
    // `system_update` event. /api/system_status used to call this too
    // but the REST endpoint is retired — WS delivery is canonical.
    static void fill_system_block(JsonObject root) {
      // ---- storage ----
      {
        JsonObject st = root["storage"].to<JsonObject>();
        const size_t total = filesystem.storageSize();
        const size_t avail = filesystem.storageAvailable();
        JsonObject fl = st["flash"].to<JsonObject>();
        fl["total_bytes"] = (uint32_t)total;
        fl["free_bytes"]  = (uint32_t)avail;
        fl["used_bytes"]  = (uint32_t)((total > avail) ? (total - avail) : 0);
        JsonObject sd = st["sd"].to<JsonObject>();
        sd["present"] = Storage::SDCard::present();
        sd["status"]  = Storage::SDCard::last_status();
        if (Storage::SDCard::present()) {
          sd["card_type"]   = Storage::SDCard::card_type_name();
          sd["total_bytes"] = (uint64_t)Storage::SDCard::total_bytes();
          sd["used_bytes"]  = (uint64_t)Storage::SDCard::used_bytes();
        }
        const auto rs = Storage::SDCard::rail_state();
        if (rs.captured) {
          JsonObject rails = sd["rails"].to<JsonObject>();
          rails["bldo1_on"] = rs.bldo1_on;
          rails["bldo1_mV"] = rs.bldo1_mV;
          rails["bldo2_on"] = rs.bldo2_on;
          rails["bldo2_mV"] = rs.bldo2_mV;
        }
      }
      // ---- rtc (hardware chip diagnostic) ----
      {
        JsonObject rtc = root["rtc"].to<JsonObject>();
        const auto rs = Sensors::PCF8563::debug_snapshot();
        rtc["available"] = Sensors::PCF8563::available();
        rtc["vl_set"]    = rs.vl_set;
        rtc["unix_ms"]   = (uint64_t)(rs.epoch * 1000.0);
      }
      // ---- sensors ----
      JsonObject sensors = root["sensors"].to<JsonObject>();
      fill_sensor_block(sensors, "gps");
      fill_sensor_block(sensors, "environment");
      fill_sensor_block(sensors, "magnetometer");
      fill_sensor_block(sensors, "imu");
      // ---- outbound staging caps + storage config ----
      {
        const auto caps = Storage::OutboundStaging::current_caps();
        JsonObject oc = root["outbound_caps"].to<JsonObject>();
        oc["max_bytes"]        = (uint32_t)caps.max_bytes;
        oc["backend"]          = Storage::OutboundStaging::backend_name(caps.chosen_backend);
        oc["flash_free_bytes"] = (uint32_t)caps.flash_free;
        oc["psram_free_bytes"] = (uint32_t)caps.psram_free;
        oc["sd_present"]       = caps.sd_present;
        if (caps.sd_present) oc["sd_free_bytes"] = (uint32_t)caps.sd_free;
      }
      // ---- user-facing storage config ----
      // Append to the already-populated `storage` object built at line
      // 1204 — using .to<JsonObject>() here overwrites the .flash /
      // .sd sub-objects (regression that made the SPA think the SD
      // card was absent). .as<JsonObject>() returns the existing
      // object so the new fields land alongside the legacy ones.
      {
        const auto& sc = Storage::Config::current();
        JsonObject st = root["storage"].as<JsonObject>();
        st["user_max_send_bytes"]      = (uint32_t)std::min<size_t>(sc.user_max_send_bytes,    0xFFFFFFFFu);
        st["user_max_receive_bytes"]   = (uint32_t)std::min<size_t>(sc.user_max_receive_bytes, 0xFFFFFFFFu);
        st["effective_max_send_bytes"] = (uint32_t)std::min<size_t>(Storage::Config::effective_max_send(),    0xFFFFFFFFu);
        st["effective_max_recv_bytes"] = (uint32_t)std::min<size_t>(Storage::Config::effective_max_receive(), 0xFFFFFFFFu);
      }
      // ---- battery (detailed) ----
      {
        const auto b = Telemetry::Battery::current();
        if (b.pmu_present) {
          JsonObject bo = root["battery"].to<JsonObject>();
          bo["percent"]      = b.percent;
          bo["state"]        = Telemetry::Battery::state_name(b.state);
          bo["voltage_v"]    = b.voltage_v;
          bo["vbus_present"] = b.vbus_present;
          if (b.vbus_present)     bo["vbus_voltage_v"] = b.vbus_voltage_v;
          if (b.has_pmu_temp)     bo["pmu_temp_c"]     = b.pmu_temp_c;
          if (b.has_discharge_ma) bo["discharge_ma"]   = b.discharge_ma;
          if (b.has_slope) {
            bo["slope_mv_per_min"] = b.slope_mv_per_min;
            bo["slope_window_ms"]  = (uint32_t)b.slope_window_ms;
          }
        }
      }
    }

    // GET /api/inbox_config — current capacity + TTL. ram_capacity is
