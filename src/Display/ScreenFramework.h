// Cross-feature OLED screen framework: one owner for the full-screen
// chrome and the button routing, with features (messenger, sensors)
// as page plugins. Tracked by issue #3.
//
// Gesture contract (depth-independent):
//   BOOT tap          next top-level screen (status -> first screen ->
//                     ... -> wraps back to status)
//   BOOT hold .7-5s   back ONE level: the active page pops an internal
//                     screen if it has one; at its root the framework
//                     exits to status
//   BOOT hold >5s     never consumed here - global gestures (pairing,
//                     console) stay reachable
//   POWER tap         on_next: advance the cursor / next item
//   POWER hold ~1s    on_select: commit whatever is highlighted
//   POWER hold 4s     PMU hardware power-off; cannot be intercepted,
//                     which is why commit sits at 1 s with margin
//
// Chrome (matches the design doc in issue #3): an 11 px INVERTED
// header bar (8x8 glyph, UPPERCASE title, live spinner at the right
// edge), the body region, and an INVERTED bottom hint bar whose lines
// follow the fixed grammar "Tap|Hold BUTTON: action" with silkscreen
// button names (POWER, BOOT). The framework draws all of that; pages
// render only the body and decide what next/select/back mean.
#pragma once

#include <Adafruit_GFX.h>
#include <Fonts/Picopixel.h>
#include <stdint.h>
#include <string.h>
#include <initializer_list>

#include "../Common/OledText.h"

